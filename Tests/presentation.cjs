const {chromium} = require(process.env.PLAYWRIGHT_PATH);
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const {pathToFileURL} = require('node:url');
const {unzipSync,strFromU8} = require('fflate');

(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1450,height:1000},acceptDownloads:true});
    const errors=[], network=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('dialog',dialog=>dialog.accept());
    page.on('request',request=>{if(/^https?:/.test(request.url())) network.push(request.url());});
    const click=id=>page.locator('#'+id).click();
    const fill=(id,value)=>page.locator('#'+id).fill(value);
    const open=name=>page.getByText(name,{exact:true}).click();
    await page.goto(pathToFileURL(path.resolve(__dirname,'../Jago-3D-Workshop.html')).href);
    await page.waitForFunction(()=>window.JagoWorkshop?.ready);
    await click('output');
    await page.locator('[data-out=model]').click();
    let pending=page.waitForEvent('download');
    await click('glb');
    const glb=await fs.readFile(await (await pending).path());
    await page.keyboard.press('Escape');
    await click('new');
    await page.waitForFunction(()=>JagoWorkshop.project.objects.length===0);
    await page.locator('#glbFile').setInputFiles({name:'Round trip.glb',mimeType:'model/gltf-binary',buffer:glb});
    await page.waitForFunction(()=>JagoWorkshop.project.objects.some(o=>o.type==='mesh'));
    const parts=await page.evaluate(()=>JagoWorkshop.project.objects.length);
    assert.ok(parts>1);

    const external=Buffer.from(JSON.stringify({asset:{version:'2.0'},buffers:[{uri:'https://example.invalid/buffer.bin',byteLength:4}]}));
    const padding=(4-external.length%4)%4;
    const rejected=Buffer.alloc(20+external.length+padding,32);
    [0x46546c67,2,rejected.length,external.length+padding,0x4e4f534a].forEach((value,index)=>rejected.writeUInt32LE(value,index*4));
    external.copy(rejected,20);
    await page.locator('#glbFile').setInputFiles({name:'External.glb',mimeType:'model/gltf-binary',buffer:rejected});
    await page.waitForFunction(()=>document.querySelector('#presentationStatus').textContent.includes('Embed all buffers'));
    assert.equal(await page.evaluate(()=>JagoWorkshop.project.objects.length),parts);
    await page.evaluate(key=>JagoWorkshop.loadExampleFixture(key),'pleated-display');
    await page.waitForFunction(()=>JagoWorkshop.project.objects[0]?.sheet?.crease);
    await open('Artwork, callouts & looks');
    await open('Callouts');
    await fill('calloutText','Fold here');
    await click('placeCallout');
    const canvas=await page.locator('#canvas').boundingBox();
    const place=()=>page.mouse.click(canvas.x+canvas.width/2,canvas.y+canvas.height/2);
    await place();
    await page.waitForFunction(()=>JagoWorkshop.project.objects[0].callouts.length===1);
    await open('Surface artwork');
    const png=Buffer.from((await page.evaluate(()=>{
      const canvas=document.createElement('canvas');
      canvas.width=32;canvas.height=16;
      const context=canvas.getContext('2d');
      context.fillStyle='#ff4010';context.fillRect(0,0,32,16);
      return canvas.toDataURL();
    })).split(',')[1],'base64');
    await page.locator('#decalFile').setInputFiles({name:'Mark.png',mimeType:'image/png',buffer:png});
    await page.waitForFunction(()=>document.querySelector('#canvas').classList.contains('surfacePlacement'));
    await place();
    await page.waitForFunction(()=>JagoWorkshop.project.objects[0].decals.length===1);
    await fill('decalAngle','25');
    await page.locator('#decalAngle').dispatchEvent('change');
    assert.equal(await page.evaluate(()=>JagoWorkshop.project.objects[0].decals[0].angle),25);

    await click('adjustDecal');
    const bounds=await page.locator('#canvas').boundingBox();
    const startX=bounds.x+bounds.width/2, startY=bounds.y+bounds.height/2;
    await page.mouse.move(startX,startY);
    await page.mouse.down();
    await page.mouse.move(startX+36,startY+15,{steps:4});
    await page.mouse.up();
    assert.equal(await page.evaluate(()=>JagoWorkshop.project.objects[0].decals[0].angle),40);
    await open('Saved looks');
    await fill('lookName','Paper');
    await click('saveLook');
    await page.evaluate(async()=>{
      const candidate=JagoWorkshop.project;
      candidate.background='#243344';
      await JagoWorkshop.load(candidate);
    });
    await fill('lookName','Night');
    await click('saveLook');
    await click('compareLooks');
    await page.waitForFunction(()=>document.querySelector('#compareLookDialog').open);
    assert.equal(await page.locator('#compareLookViews canvas').count(),2);
    const previews=await page.locator('#compareLookViews canvas').evaluateAll(items=>items.map(canvas=>canvas.toDataURL()));
    assert.notEqual(previews[0],previews[1]);
    await page.keyboard.press('Escape');
    await page.locator('#lookSelect').selectOption('0');
    await click('applyLook');
    await page.waitForFunction(()=>JagoWorkshop.project.background==='#26323a');

    await click('output');
    await page.locator('[data-out=image]').click();
    await open('Presentation sheet');
    pending=page.waitForEvent('download');
    await click('presentationExport');
    const zip=unzipSync(await fs.readFile(await (await pending).path()));
    assert.deepEqual(Object.keys(zip),['presentation.png','view-1.png','view-2.png','view-3.png','flat-pattern.svg']);
    assert.equal(zip['presentation.png'][0],137);
    assert.equal(Buffer.from(zip['presentation.png']).readUInt32BE(16),2630);
    assert.match(strFromU8(zip['flat-pattern.svg']),/score-mountain/);
    const checks=path.resolve(__dirname,'../Checks');
    await fs.mkdir(checks,{recursive:true});
    await fs.writeFile(path.join(checks,'presentation.png'),zip['presentation.png']);
    await page.keyboard.press('Escape');
    const saved=await page.evaluate(()=>JagoWorkshop.project);
    await page.evaluate(project=>JagoWorkshop.load(project),saved);
    assert.equal(await page.evaluate(()=>JagoWorkshop.project.objects[0].decals.length),1);
    assert.equal(await page.evaluate(()=>JagoWorkshop.project.variants.length),2);
    assert.deepEqual(errors,[]);
    assert.deepEqual(network,[]);
    console.log('PASS GLB round trip, decal placement, callouts, look comparison, presentation ZIP and reload offline');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
